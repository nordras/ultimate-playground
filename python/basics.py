# ------------------------------------------------------------
# 1. Variables and Data Types
# ------------------------------------------------------------

integer = 42
floating = 3.14
text = "Hello, Python!"
boolean = True
null = None

print(type(integer))   # <class 'int'>
print(type(floating))  # <class 'float'>
print(type(text))      # <class 'str'>
print(type(boolean))   # <class 'bool'>
print(type(null))      # <class 'NoneType'>

